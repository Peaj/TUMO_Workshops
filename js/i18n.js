const events = emitter();
let lang = load("lang", "de") === "en" ? "en" : "de";
document.documentElement.lang = lang;

export const onLangChange = events.on;
export const getLang = () => lang;

export function setLang(next) {
  if (next !== "de" && next !== "en") return;
  lang = next;
  save("lang", lang);
  document.documentElement.lang = lang;
  events.emit(lang);
}

const other = () => (lang === "de" ? "en" : "de");

/** UI string with {placeholders}. */
export function t(key, vars = {}) {
  const template = STRINGS[lang][key] ?? STRINGS[other()][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? vars[name] : `{${name}}`));
}

/** Content string from a {de, en} pair, falling back to the other language. */
export function tx(pair) {
  if (pair == null) return "";
  if (typeof pair === "string") return pair;
  return pair[lang] || pair[other()] || "";
}
